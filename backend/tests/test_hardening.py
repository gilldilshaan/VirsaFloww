import os
import re
import json
import pytest
from backend.app.core.config import settings

def test_users_seed_hashes_scrypt_format():
    """H1 & Amendment 8: Confirm users.json contains only scrypt-format hashes and no plaintext."""
    users_file = os.path.join(settings.SEED_DIR, "users.json")
    assert os.path.exists(users_file), f"Seed users file not found at {users_file}"

    with open(users_file, "r", encoding="utf-8") as f:
        users = json.loads(f.read())

    assert len(users) >= 6, "Expected at least 6 demo users in seed"

    hex_128_pattern = re.compile(r"^[0-9a-f]{128}$")

    for u in users:
        assert "passwordHash" in u, f"User {u.get('id')} missing passwordHash field"
        p_hash = u["passwordHash"]
        assert isinstance(p_hash, str)
        # Verify 128-char hex digest generated by hashlib.scrypt (64 bytes in hex)
        assert hex_128_pattern.match(p_hash), (
            f"User {u.get('id')} passwordHash does not match scrypt 128-character hex format: {p_hash}"
        )
        # Ensure no plaintext passwords leaked in user record
        assert "password" not in u
        assert "admin12345" not in json.dumps(u)
        assert "farmer12345" not in json.dumps(u)

def test_no_env_file_tracked():
    """H1: Confirm that no .env file is tracked in git."""
    repo_root = settings.REPO_ROOT
    git_dir = os.path.join(repo_root, ".git")
    if not os.path.exists(git_dir):
        pytest.skip(".git directory not present")

    # Inspect tracked files using git ls-files if available
    try:
        import subprocess
        res = subprocess.run(["git", "ls-files"], cwd=repo_root, capture_output=True, text=True, check=True)
        tracked = res.stdout.splitlines()
        for f in tracked:
            basename = os.path.basename(f)
            if basename.startswith(".env") and basename != ".env.example":
                pytest.fail(f"Tracked environment secret file found: {f}")
    except Exception:
        pass

