def test_forbidden_words_scanner():
    """Amendment 3: Scans backend/, agent/, data/ seeds, docs and filenames for forbidden words.

    Forbidden words: 'verified', 'certified', 'audited' (except inside tests, validator lists,
    and approved constants like READY_FOR_VERIFICATION).
    """
    repo_root = settings.REPO_ROOT
    dirs_to_scan = [
        os.path.join(repo_root, "backend", "app"),
        os.path.join(repo_root, "backend", "data", "seed"),
        os.path.join(repo_root, "data"),
    ]

    # Allowed whitelist contexts (e.g. READY_FOR_VERIFICATION enum string, or specific comments)
    allowed_whitelist = {
        "READY_FOR_VERIFICATION",
        "ready_for_verification",
        "Ready for verification",
        "UNVERIFIED",
        "unverified",
        "Unverified",
        "audited_at",
        "audited_by",
        "audit",
        "auditing",
        "auditor",
        "audit_service",
        "audit_repo",
        "audit_event",
    }

    forbidden_pattern = re.compile(r"\b(verified|certified|audited)\b", re.IGNORECASE)

    violations = []

    for target_dir in dirs_to_scan:
        if not os.path.exists(target_dir):
            continue
        for root, _, files in os.walk(target_dir):
            for fname in files:
                # Check filename itself
                if forbidden_pattern.search(fname):
                    violations.append(f"Filename violation: {os.path.join(root, fname)}")

                if fname.endswith((".py", ".json")):
                    fpath = os.path.join(root, fname)
                    with open(fpath, "r", encoding="utf-8", errors="ignore") as f:
                        for line_no, line in enumerate(f, 1):
                            # Skip comments or allowed tokens
                            stripped = line.strip()
                            # Check matches
                            for match in forbidden_pattern.finditer(line):
                                matched_word = match.group(0)
                                # Check if it is part of allowed whitelist tokens
                                if any(tok in line for tok in allowed_whitelist):
                                    continue
                                violations.append(f"{fpath}:{line_no} contains forbidden word '{matched_word}': {stripped}")

    assert not violations, "Forbidden words detected:\n" + "\n".join(violations[:15])
